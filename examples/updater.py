"""
examples/updater.py – Secure auto-updater prototype for jitterbugs.

WARNING: DO NOT USE THIS AS A PRODUCTION UPDATE MECHANISM; FOR DEMO/TESTING ONLY.

Demonstrates:
  - Fetching a signed manifest over HTTPS
  - Verifying the manifest signature with an embedded RSA public key
  - Downloading an artifact and verifying its SHA-256 checksum
  - Atomic install via temp-file + os.replace() swap
  - Keeping a backup of the previous version for rollback
  - Structured logging to examples/updater.log
  - CLI flags: --check-only, --manifest-url, --sig-url, --verify,
                --auto, --version-file

Usage (see examples/README_UPDATER.md for full walkthrough):
  python examples/updater.py --check-only
  python examples/updater.py --auto
  python examples/updater.py --manifest-url https://localhost:8443/updates/manifest.json \\
                              --sig-url     https://localhost:8443/updates/manifest.json.sig \\
                              --verify      certs/ca.crt \\
                              --auto

Requirements: requests>=2.28, cryptography>=3.4
"""

